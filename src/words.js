/**
 * 카드 한 장 — 난이도가 정한 만큼 칸마다 뽑아 여섯 개를 섞어 낸다.
 * mix 는 { easy, medium, hard } 이고 합이 여섯이다.
 */
export function card(rand, mix) {
  const m = mix || { easy: 2, medium: 2, hard: 2 };
  const take = (arr, n) => {
    const out = [];
    const room = Math.min(n, arr.length);
    while (out.length < room) {
      const w = arr[Math.floor(rand() * arr.length)];
      if (!out.includes(w)) out.push(w);
    }
    return out;
  };
  const six = [...take(EASY, m.easy), ...take(MEDIUM, m.medium), ...take(HARD, m.hard)];
  for (let i = six.length - 1; i > 0; i--) {          // 난이도 순서가 드러나지 않게 섞는다
    const j = Math.floor(rand() * (i + 1));
    [six[i], six[j]] = [six[j], six[i]];
  }
  return six;
}
